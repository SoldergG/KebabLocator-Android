    val hasTakeaway: Boolean,
    val isSponsored: Boolean = false,
    val isVerified: Boolean = false,
    val contributorId: String? = null,
    val imageUrl: String? = null
) {

    /** Check if the shop is currently open based on device time */
    val isOpenNow: Boolean
        get() {
            val hour = Calendar.getInstance().get(Calendar.HOUR_OF_DAY)
            return if (closeHour > openHour) {
                hour >= openHour && hour < closeHour
            } else {
                hour >= openHour || hour < closeHour
            }
        }

    /** Formatted open status string */
    val statusText: String
        get() = if (isOpenNow) "Open Now" else "Closed"

    /** Distance from a given coordinate in kilometers using Location.distanceBetween */
    fun distanceFrom(lat: Double, lon: Double): Double {
        val results = FloatArray(1)
        Location.distanceBetween(latitude, longitude, lat, lon, results)
        return results[0].toDouble() / 1000.0 // convert metres to km
    }

    /** Returns the best available image URL string for display */
    fun displayImageURL(): String? {
        if (!imageUrl.isNullOrEmpty() && imageUrl.startsWith("http")) {
            return imageUrl
        }
        if (imageName.startsWith("http")) {
            return imageName
        }
        return null
    }

