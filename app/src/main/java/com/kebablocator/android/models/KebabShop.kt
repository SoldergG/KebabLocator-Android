// MARK: - Supabase DTO for JSON Parsing

data class SupabaseShopDTO(
    @SerializedName("id") val id: String,
    @SerializedName("name") val name: String,
    @SerializedName("rating") val rating: Double,
    @SerializedName("reviews") val reviews: Int,
    @SerializedName("address") val address: String,
    @SerializedName("latitude") val latitude: Double,
    @SerializedName("longitude") val longitude: Double,
    @SerializedName("tags") val tags: List<String>,
    @SerializedName("price") val price: String,
    @SerializedName("hours") val hours: String,
    @SerializedName("open_hour") val openHour: Int,
    @SerializedName("close_hour") val closeHour: Int,
    @SerializedName("description") val description: String,
    @SerializedName("category") val category: String,
    @SerializedName("phone") val phone: String?,
    @SerializedName("website") val website: String?,
    @SerializedName("popular_dishes") val popularDishes: List<String>,
    @SerializedName("has_delivery") val hasDelivery: Boolean,
    @SerializedName("has_dine_in") val hasDineIn: Boolean,
    @SerializedName("has_takeaway") val hasTakeaway: Boolean,
    @SerializedName("image_url") val imageUrl: String?,
    @SerializedName("is_sponsored") val isSponsored: Boolean = false,
    @SerializedName("is_verified") val isVerified: Boolean = false,
    @SerializedName("contributor_id") val contributorId: String?
)

/** Convert a Supabase DTO to the app's domain model */
fun SupabaseShopDTO.toKebabShop(): KebabShop {
    return KebabShop(
        id = id,
        name = name,
        rating = rating,
        reviews = reviews,
        address = address,
        latitude = latitude,
        longitude = longitude,
        tags = tags,
        price = price,
        hours = hours,
        openHour = openHour,
        closeHour = closeHour,
        description = description,
        imageName = "",
        category = KebabCategory.fromDisplayName(category),
        phone = phone ?: "",
        website = website ?: "",
        popularDishes = popularDishes,
        hasDelivery = hasDelivery,
        hasDineIn = hasDineIn,
        hasTakeaway = hasTakeaway,
        isSponsored = isSponsored,
        isVerified = isVerified,
        contributorId = contributorId,
        imageUrl = imageUrl
    )
}
