enum class KebabCategory(val displayName: String, val emoji: String, val iconName: String) {
    DONER("D\u00F6ner", "\uD83E\uDD59", "local_fire_department"),
    FALAFEL("Falafel", "\uD83E\uDDC6", "eco"),
    DURUM("D\u00FCr\u00FCm", "\uD83C\uDF2F", "receipt_long"),
    SHAWARMA("Shawarma", "\uD83E\uDD69", "groups"),
    MIXED("Mixed Plate", "\uD83C\uDF7D\uFE0F", "takeout_dining");

    companion object {
        fun fromDisplayName(name: String): KebabCategory {
            return entries.firstOrNull { it.displayName.equals(name, ignoreCase = true) } ?: MIXED
        }
    }
}

